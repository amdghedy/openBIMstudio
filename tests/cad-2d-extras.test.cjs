const { execSync } = require("child_process"); const fs=require("fs"),os=require("os"),path=require("path"),assert=require("assert");
const out=fs.mkdtempSync(path.join(os.tmpdir(),"cadx-"));
execSync(`npx tsc src/modules/cad-viewer/cad-2d-extras.ts --outDir ${out} --module commonjs --target es2020 --skipLibCheck --ignoreDeprecations 5.0 ${process.env.TSC_IGNORE_CONFIG?"--ignoreConfig":""}`,{stdio:"pipe"});
const find=(d,n)=>{for(const f of fs.readdirSync(d,{withFileTypes:true})){const p=path.join(d,f.name);if(f.isDirectory()){const r=find(p,n);if(r)return r}else if(f.name===n)return p}};
const X=require(find(out,"cad-2d-extras.js"));
let pass=0,fail=0;const t=(n,f)=>{try{f();pass++;console.log("  PASS "+n)}catch(e){fail++;console.log("  FAIL "+n+": "+e.message)}};
const T=(v,x,y)=>({type:"TEXT",layer:"0",position:{x,y},height:2.5,value:v});
t("case modes",()=>{const e=[T("hello wORLD. next one",0,0)];
 X.changeTextCase(e,[0],"upper");assert.equal(e[0].value,"HELLO WORLD. NEXT ONE");
 X.changeTextCase(e,[0],"title");assert.equal(e[0].value,"Hello World. Next One");
 X.changeTextCase(e,[0],"sentence");assert.equal(e[0].value,"Hello world. Next one");
 X.changeTextCase(e,[0],"lower");assert.equal(e[0].value,"hello world. next one");});
t("case follows runs and skips non-text",()=>{const e=[{...T("ab",0,0),runs:[{text:"a"},{text:"b"}]},{type:"LINE",layer:"0",start:{x:0,y:0},end:{x:1,y:1}}];
 assert.equal(X.changeTextCase(e,[0,1],"upper"),1);assert.deepEqual(e[0].runs.map(r=>r.text),["A","B"]);});
t("replace literal, case-insensitive, special chars",()=>{const e=[T("Wall (W1) wall",0,0),T("none",1,1)];
 assert.equal(X.replaceInText(e,[0,1],"wall","Slab"),1);assert.equal(e[0].value,"Slab (W1) Slab");
 assert.equal(X.replaceInText(e,[0],"(W1)","$&"),1);assert.equal(e[0].value,"Slab $& Slab");
 assert.equal(X.replaceInText(e,[0],"",""),0);});
t("replace match case",()=>{const e=[T("Ab ab",0,0)];X.replaceInText(e,[0],"ab","X",true);assert.equal(e[0].value,"Ab X");});
t("tcount reading order",()=>{const e=[T("a",5,0),T("b",0,10),T("c",9,10)];
 assert.equal(X.numberTexts(e,[0,1,2],1,2,"P-","m"),3);
 assert.deepEqual(e.map(x=>x.value),["P-5m","P-1m","P-3m"]);});
t("snap to grid",()=>{const e=[{type:"LINE",layer:"0",start:{x:1.2,y:2.6},end:{x:9.9,y:0.4}},{type:"CIRCLE",layer:"0",center:{x:4.4,y:4.6},radius:1}];
 assert.equal(X.snapToGrid(e,[0,1],1),2);assert.deepEqual(e[0].start,{x:1,y:3});assert.deepEqual(e[0].end,{x:10,y:0});assert.deepEqual(e[1].center,{x:4,y:5});
 assert.equal(X.snapToGrid(e,[0],0),0);});
t("align centers x/y",()=>{const e=[{type:"LINE",layer:"0",start:{x:0,y:0},end:{x:10,y:0}},{type:"CIRCLE",layer:"0",center:{x:2,y:5},radius:1}];
 assert.equal(X.alignCenters(e,[0,1],"x"),2);assert.equal(e[1].center.x,5);
 assert.equal(X.alignCenters(e,[0],"x"),0);});
t("circle to polyline",()=>{const e=[{type:"CIRCLE",layer:"L",center:{x:1,y:1},radius:2}];
 const o=X.circlesToPolylines(e,[0],8);assert.equal(o.length,1);assert.equal(o[0].points.length,8);assert.equal(o[0].closed,true);assert.equal(o[0].layer,"L");
 for(const p of o[0].points)assert.ok(Math.abs(Math.hypot(p.x-1,p.y-1)-2)<1e-9);
 assert.equal(X.circlesToPolylines(e,[0],1)[0].points.length,3);});
t("vertices to points dedupes",()=>{const e=[{type:"LWPOLYLINE",layer:"A",points:[{x:0,y:0},{x:1,y:0}],closed:false},{type:"LINE",layer:"B",start:{x:1,y:0},end:{x:2,y:2}}];
 const o=X.verticesToPoints(e,[0,1],"0");assert.equal(o.length,3);assert.ok(o.every(p=>p.type==="POINT"));});
t("import-loss description is ordered, ignores zero counts, empty when nothing dropped",()=>{
 assert.equal(X.describeUnsavedSkipped(undefined),"");assert.equal(X.describeUnsavedSkipped({MLINE:0}),"");
 assert.equal(X.describeUnsavedSkipped({"3DSOLID":2,MLINE:5,ACAD_TABLE:2}),"5 MLINE, 2 3DSOLID, 2 ACAD_TABLE");});
console.log(`${pass} passed, ${fail} failed`);process.exit(fail?1:0);

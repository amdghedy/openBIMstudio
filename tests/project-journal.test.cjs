const { execSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const out = fs.mkdtempSync(path.join(os.tmpdir(), "obs-project-journal-"));
execSync(`npx tsc src/modules/projects/project-journal.ts --outDir "${out}" --module commonjs --target ES2022 --moduleResolution node --lib ES2022,DOM --skipLibCheck --noCheck`, { cwd: root, stdio: "inherit" });
const find = (dir, name) => { for (const entry of fs.readdirSync(dir, { withFileTypes: true })) { const file = path.join(dir, entry.name); if (entry.isDirectory()) { const nested = find(file, name); if (nested) return nested; } else if (entry.name === name) return file; } };
const journal = require(find(out, "project-journal.js"));
assert.equal(journal.PROJECT_RECOVERY_RETENTION, 10);
assert.equal(journal.getModelBlobVersionKey("p-1", "ifc-1", "v2"), "p-1::ifc-1::v2");
assert.deepEqual(journal.getUnreferencedModelBlobVersionKeys(["a", "b", "c"], new Set(["b"])), ["a", "c"]);
assert.deepEqual(journal.getProjectJournalPruneIds([1, 2, 3, 4], 10), []);
assert.deepEqual(journal.getProjectJournalPruneIds([1, 2, 3, 4, 5], 3), [1, 2]);
assert.deepEqual(journal.getProjectJournalPruneIds([9, 2, 8, 1, 9, 7], 3), [1, 2]);
assert.throws(() => journal.getProjectJournalPruneIds([1], 0), /positive integer/);
const doc = { id: "p-1", name: "Tower", createdAt: 10, updatedAt: 20, elements: [{ id: "wall-1" }, { id: "wall-2" }], models: [{ id: "ifc-1", name: "structure.ifc", bytes: 100 }, { id: "frag-1", name: "services.frag", bytes: 200 }] };
const summary = journal.summarizeProjectJournalRecord({ id: 7, projectId: "p-1", createdAt: 30, reason: "project-save", doc, modelVersions: [{ modelId: "ifc-1", version: "v1" }], archivedModelIds: ["ifc-1"], missingModelIds: ["frag-1"] });
assert.equal(summary.archivedModelCount, 1); assert.equal(summary.missingModelCount, 1);
const restored = journal.prepareRecoveredProjectDocument(doc, new Set(["ifc-1"]), 99);
assert.equal(restored.doc.updatedAt, 99); assert.equal(restored.doc.models[0].missing, undefined); assert.equal(restored.doc.models[1].missing, true);
assert.deepEqual(restored.missingModelIds, ["frag-1"]); assert.equal(doc.updatedAt, 20);
console.log("PASS project recovery retention, summaries, and missing-payload semantics");

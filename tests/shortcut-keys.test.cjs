const { execSync } = require("child_process");
const fs = require("fs"), path = require("path"), assert = require("assert");
const out = fs.mkdtempSync(path.join(require("os").tmpdir(), "sk-"));
execSync(`npx tsc src/modules/shortcuts/shortcut-keys.ts --outDir ${out} --module commonjs --target es2020 --skipLibCheck`, { stdio: "pipe" });
const m = require(path.join(out, "shortcut-keys.js"));
let n = 0; const ok = (c, s) => { assert.ok(c, s); n++; };
ok(m.normalizeKeys("WA") === "wa", "two letters");
ok(m.normalizeKeys("Ctrl+Shift+Z") === "ctrl+shift+z", "combo");
ok(m.normalizeKeys("shift+ctrl+z") === "ctrl+shift+z", "order");
ok(m.normalizeKeys("Cmd+S") === "ctrl+s", "cmd");
ok(m.normalizeKeys("F5") === "f5", "f5");
ok(m.normalizeKeys("abc") === null && m.normalizeKeys("") === null && m.normalizeKeys("ctrl+") === null, "invalid");
ok(m.normalizeKeys("ctrl+ctrl+a") === null && m.normalizeKeys("foo+a") === null, "bad mods");
ok(m.prettyKeys("wa") === "WA" && m.prettyKeys("ctrl+shift+z") === "Ctrl+Shift+Z", "pretty");
ok(m.comboFromEvent({ key: "k", ctrlKey: true, metaKey: false, shiftKey: false, altKey: false }) === "ctrl+k", "event");
ok(m.comboFromEvent({ key: "Shift", ctrlKey: false, metaKey: false, shiftKey: true, altKey: false }) === null, "lone modifier");
ok(m.comboFromEvent({ key: "F5", ctrlKey: false, metaKey: false, shiftKey: false, altKey: false }) === "f5", "F5");
ok(m.findConflict({ a: "ks", b: "wa" }, "b", "ks") === "a" && m.findConflict({ a: "ks" }, "a", "ks") === null, "conflict");
console.log(`shortcut-keys: ${n} checks OK`);

const { execSync } = require("child_process");
const fs = require("fs"), path = require("path"), assert = require("assert");
const out = fs.mkdtempSync(path.join(require("os").tmpdir(), "ss-"));
execSync(`npx tsc src/features/shortcuts.ts --outDir ${out} --module commonjs --target es2020 --skipLibCheck`, { stdio: "pipe" });
let kd; const timers = [];
global.window = { addEventListener: (t, f) => { if (t === "keydown") kd = f; }, setTimeout: (f) => { timers.push(f); return timers.length; } };
global.clearTimeout = (i) => { if (i) timers[i - 1] = null; };
const { shortcuts } = require(path.join(out, "shortcuts.js"));
const fired = []; const reg = (id, keys) => shortcuts.register({ id, label: id, keys, category: "tool", handler: () => fired.push(id) });
reg("ks", "ks"); reg("ksx", "ksx"); reg("wa", "wa"); reg("s", "s"); reg("abc", "abc");
shortcuts.install();
const press = (k) => kd({ key: k, ctrlKey: false, metaKey: false, shiftKey: false, altKey: false, target: null, preventDefault() {}, stopImmediatePropagation() {} });
const flush = () => { for (let i = 0; i < timers.length; i++) { const f = timers[i]; timers[i] = null; if (f) f(); } };
let n = 0; const ok = (c, m) => { assert.ok(c, m); n++; };
press("a"); press("b"); press("c"); ok(fired.pop() === "abc" && !fired.length, "three letters fire immediately");
press("w"); press("a"); ok(fired.pop() === "wa", "two letters");
press("k"); press("s"); ok(!fired.length, "ks waits (ksx exists)"); flush(); ok(fired.pop() === "ks", "ks fires after timeout");
press("k"); press("s"); press("x"); ok(fired.pop() === "ksx" && !fired.length, "ksx fires");
press("s"); ok(fired.pop() === "s", "single s");
press("k"); press("w"); press("a"); ok(fired.pop() === "wa", "broken sequence restarts");
console.log(`shortcut-sequences: ${n} checks OK`);

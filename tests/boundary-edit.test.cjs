const { execSync } = require("child_process"); const fs=require("fs"),os=require("os"),path=require("path"),assert=require("assert");
const out=fs.mkdtempSync(path.join(os.tmpdir(),"be-"));
execSync(`npx tsc src/modules/views/boundary-edit.ts --outDir ${out} --module commonjs --target es2020 --skipLibCheck --ignoreConfig --ignoreDeprecations 6.0`,{stdio:"inherit"});
const m=require(path.join(out,"boundary-edit.js"));
let pass=0,fail=0;const t=(n,f)=>{try{f();pass++;console.log("  PASS "+n)}catch(e){fail++;console.log("  FAIL "+n+": "+e.message)}};
const sq=[[0,0],[4,0],[4,4],[0,4]];
t("area",()=>assert.strictEqual(Math.abs(m.polygonArea(sq)),16));
t("insert vertex after edge",()=>{const p=m.insertVertex(sq,0,[2,-1]);assert.deepStrictEqual(p[1],[2,-1]);assert.strictEqual(p.length,5);assert.strictEqual(sq.length,4)});
t("insert on closing edge appends",()=>{const p=m.insertVertex(sq,3,[-1,2]);assert.deepStrictEqual(p[4],[-1,2])});
t("remove vertex",()=>assert.strictEqual(m.removeVertex(sq,1).length,3));
t("cannot go below 3 vertices",()=>assert.strictEqual(m.removeVertex([[0,0],[1,0],[0,1]],0),null));
t("move vertex is immutable",()=>{const p=m.moveVertex(sq,2,[9,9]);assert.deepStrictEqual(p[2],[9,9]);assert.deepStrictEqual(sq[2],[4,4])});
t("hit vertex within tolerance",()=>{assert.strictEqual(m.hitVertex(sq,4.05,0.02,0.1),1);assert.strictEqual(m.hitVertex(sq,2,2,0.1),-1)});
t("midpoint",()=>assert.deepStrictEqual(m.edgeMidpoint(sq,3),[0,2]));
t("valid square",()=>assert.ok(m.isValidBoundary(sq)));
t("bow-tie is invalid",()=>assert.ok(!m.isValidBoundary([[0,0],[4,4],[4,0],[0,4]])));
t("degenerate is invalid",()=>assert.ok(!m.isValidBoundary([[0,0],[1,1],[2,2]])));
t("concave L is valid",()=>assert.ok(m.isValidBoundary([[0,0],[4,0],[4,2],[2,2],[2,4],[0,4]])));
console.log(`=== Result: ${pass} passed, ${fail} failed ===`);process.exit(fail?1:0);

/* Independent external-parser validation of DXF import and export.
 *
 * Every other DXF/DWG test in this repository reads files back with code from
 * THIS repository (the TypeScript reader, or the acadrust WASM engine that the
 * writer feeds). That proves internal coherence only. This test is different:
 * it validates through ezdxf (https://ezdxf.readthedocs.io), an independent
 * Python implementation of the DXF format that shares no code with
 * openBIMstudio's reader/writer and with the acadrust engine.
 *
 * What passing means here:
 *   - files the DXF writer produces load in a third-party parser with a clean
 *     structural audit, and the entities/layers/text/units that arrive there
 *     are the ones that were written;
 *   - files authored by a third-party implementation (the committed corpus is
 *     generated by ezdxf itself, see tests/fixtures/dxf-corpus/generate.py)
 *     are read by the platform's reader with the layers, units, geometry,
 *     text, block content, dimension geometry and styles the file actually
 *     contains, and entity types outside the 2D model are counted and
 *     reported (doc.skipped), never dropped silently.
 *
 * What passing does NOT mean (honesty rules, see docs/DXF_DWG_INTEROP.md):
 *   - it is NOT proof that AutoCAD/BRX/microstation open these files - no
 *     desktop CAD application was run here;
 *   - it is NOT proof for DWG: DWG export is cross-validated with LibreDWG in
 *     tests/cad-dwg-export.test.cjs, a different independent implementation;
 *   - the internal read-back legs inside this test are labelled as internal.
 *
 * Runs ezdxf via scripts/validate_dxf_external.py. Skips (exit 0) when
 * python3/ezdxf is unavailable; CI installs ezdxf.
 */
const fs = require("fs"), os = require("os"), path = require("path"), assert = require("assert");
const { execSync, spawnSync } = require("child_process");
const root = path.join(__dirname, "..");
const CORPUS = path.join(root, "tests", "fixtures", "dxf-corpus");
const VALIDATOR = path.join(root, "scripts", "validate_dxf_external.py");

// 0. ezdxf available? (pip install ezdxf). CI installs it; local dev may not.
const probe = spawnSync("python3", ["-c", "import ezdxf"], { encoding: "utf8" });
if (probe.status !== 0) {
  console.log("SKIP: python3 ezdxf not available - the independent DXF validation needs `pip install ezdxf`");
  process.exit(0);
}

// 1. Compile the platform's reader + writer with tsc (same pattern as the
//    other drawing tests): the exact production code paths, no mocks.
const out = fs.mkdtempSync(path.join(os.tmpdir(), "dxf-indep-"));
execSync(`npx tsc src/modules/drawings/dxf-reader.ts src/modules/drawings/dxf-writer.ts --outDir ${out} --module commonjs --target es2020 --skipLibCheck --esModuleInterop`, { cwd: root, stdio: "pipe" });
const find = (d, n) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) { const r = find(p, n); if (r) return r; } else if (f.name === n) return p; } };
const { parseDxf } = require(find(out, "dxf-reader.js"));
const { writeDxf } = require(find(out, "dxf-writer.js"));

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "dxf-indep-f-"));
let pass = 0, fail = 0;
const t = (n, f) => { try { f(); pass++; console.log("  PASS " + n); } catch (e) { fail++; console.log("  FAIL " + n + ": " + e.message); } };
const near = (a, b, eps = 1e-6) => assert.ok(Math.abs(a - b) <= eps, `${a} != ${b} (±${eps})`);
const near2 = (p, q, eps = 1e-6) => { near(p.x ?? p[0], q.x ?? q[0], eps); near(p.y ?? p[1], q.y ?? q[1], eps); };

/** Run the external validator on a corpus fixture. */
const ext = (name) => JSON.parse(execSync(`python3 "${VALIDATOR}" "${path.join(CORPUS, name)}"`, { encoding: "utf8" }));
/** Run the external validator on raw DXF text written to a temp file. */
const extRaw = (text, name) => { const p = path.join(tmp, name); fs.writeFileSync(p, text); return JSON.parse(execSync(`python3 "${VALIDATOR}" "${p}"`, { encoding: "utf8" })); };
/** Parse a corpus fixture with the platform reader. */
const ours = (name) => { const r = parseDxf(fs.readFileSync(path.join(CORPUS, name), "utf8")); return r.doc ?? r; };

const INUNITS = { 0: "unitless", 1: "in", 2: "ft", 4: "mm", 5: "cm", 6: "m" };

console.log("PART A - import fidelity: ezdxf-authored corpus vs the platform reader (ground truth = ezdxf)");

/* ── A1. Units: same wall, three $INSUNITS, coordinates preserved ───────── */
{
  const specs = [
    { f: "units_mm.dxf", s: 1.0 },
    { f: "units_m.dxf", s: 0.001 },
    { f: "units_in.dxf", s: 1 / 25.4 },
  ];
  for (const { f, s } of specs) {
    const x = ext(f), o = ours(f);
    t(`${f}: $INSUNITS ${x.insunits} -> "${INUNITS[x.insunits]}"`, () => {
      assert.strictEqual(o.units, INUNITS[x.insunits]);
    });
    t(`${f}: wall coordinates match ezdxf exactly`, () => {
      const line = x.sample.LINE.find((l) => l.layer === "WALLS");
      assert.ok(line, "ezdxf reports the WALLS line");
      const wall = o.entities.find((e) => e.type === "LINE" && e.layer === "WALLS");
      assert.ok(wall, "our reader has the WALLS line");
      near2(wall.start, line.start); near2(wall.end, line.end);
      // independent length check straight from the specification
      near(Math.hypot(line.end[0] - line.start[0], line.end[1] - line.start[1]), 100 * s, 1e-9);
    });
    t(`${f}: text value and layer preserved`, () => {
      const xt = x.sample.TEXT[0];
      const ot = o.entities.find((e) => e.type === "TEXT");
      assert.ok(ot, "text imported");
      assert.strictEqual(ot.value, xt.text);
      assert.strictEqual(ot.layer, xt.layer);
      near(ot.height, xt.height, 1e-9);
    });
  }
}

/* ── A2. Layers, linetypes, true colour, lineweight, LTSCALE ────────────── */

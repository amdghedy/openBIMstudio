#!/usr/bin/env bash
# Evidence check: for each hardening issue, test whether its deliverables exist on main.
cd /home/z/my-project/openBIMstudio || exit 1
chk() { # chk <label> <test...>
  local label="$1"; shift
  if eval "$@" >/dev/null 2>&1; then echo "  YES  $label"; else echo "  no   $label"; fi
}
echo "P0-01 crash containment:"
chk "src/core/crashLog.ts"                    "[ -f src/core/crashLog.ts ]"
chk "AppErrorBoundary component"              "find src -name 'AppErrorBoundary*' | grep -q ."
chk "window.onerror handlers wired"           "grep -rl 'window.onerror\|unhandledrejection' src/main.tsx src/shell 2>/dev/null | grep -q ."
chk "crash-log viewer in UI"                  "grep -rli 'crashlog\|crash log' src --include='*.tsx' | grep -q ."
echo "P0-02 safeLoad:"
chk "src/core/safeLoad.ts"                    "[ -f src/core/safeLoad.ts ]"
chk "schema definitions"                      "grep -rln 'ProjectFileSchema\|BcfManifestSchema' src | grep -q ."
chk "loaders routed through safeLoad"         "grep -rln 'safeLoad(' src --include='*.ts*' | grep -v 'core/safeLoad' | grep -q ."
chk "malformed fixtures corpus"               "[ -d tests/fixtures/malformed ] || [ -d test/fixtures/malformed ]"
chk "CI grep audit for safeLoad"              "grep -rn 'safeLoad' .github/workflows/*.yml scripts/check*.mjs 2>/dev/null | grep -q ."
echo "P0-03 backup-on-load:"
chk "src/core/backup.ts"                      "[ -f src/core/backup.ts ]"
chk "backupBeforeWrite wired"                 "grep -rn 'backupBeforeWrite' src --include='*.ts*' | grep -q ."
echo "P0-04 fail-closed server:"
chk "api/ server code"                        "[ -d api ] && [ -n \"$(ls api 2>/dev/null)\" ]"
chk "origin allow-list"                       "grep -rn 'ALLOWED_ORIGIN\|allowedOrigins\|origin' api/*.ts api/*.js 2>/dev/null | grep -qi allow"
chk "rate limiting"                           "grep -rni 'rate.?limit' api 2>/dev/null | grep -q ."
echo "P0-05 deps hygiene:"
chk "jsonpath-plus removed"                   "! grep -q 'jsonpath-plus' package.json"
chk "npm audit CI gate"                       "grep -rn 'npm audit\|audit_ci' .github/workflows/*.yml | grep -q ."
echo "P1-01 registry + frozen globals:"
chk "src/core/registry.ts"                    "[ -f src/core/registry.ts ]"
chk "ESLint rule for __obs globals"           "grep -rn '__obs' hardening.eslintrc.json .eslintrc* eslint.config* 2>/dev/null | grep -q ."
echo "P1-02 TS strictification:"
chk "strict in tsconfig"                      "grep -q '\"strict\": true' tsconfig.json"
echo "P1-03 golden corpus:"
chk "test/fixtures/ifc-corpus"                "[ -d test/fixtures/ifc-corpus ] || [ -d tests/fixtures/ifc-corpus ]"
echo "P1-04 roundtrip pipeline:"
chk "scripts/golden-roundtrip.mjs"            "[ -f scripts/golden-roundtrip.mjs ]"
chk "CI workflow activated on push"           "grep -A2 '^on:' .github/workflows/golden-roundtrip.yml | grep -q 'push'"
echo "P1-05 property-based invariants:"
chk "fast-check in devDeps"                   "grep -q 'fast-check' package.json"
chk "property test files"                     "find src tests test -name '*.prop.test.*' -o -name '*.property.*' 2>/dev/null | grep -q ."
echo "P1-06 malformed property tests:"
chk "malformed input tests"                   "grep -rln 'truncated\|malformed' tests test src --include='*.test.*' 2>/dev/null | grep -q ."
echo "P1-07 Playwright E2E:"
chk "@playwright/test in devDeps"             "grep -q '@playwright/test' package.json"
chk "playwright config"                       "[ -f playwright.config.ts ] || [ -f playwright.config.js ]"
echo "P2-01 journal persistence:"
chk "src/core/journal.ts"                     "[ -f src/core/journal.ts ]"
chk "journal wired into persistence layer"    "grep -rln 'from.*core/journal\|core/journal' src --include='*.ts*' | grep -v 'core/journal' | grep -q ."
echo "P2-02 tool-catalog CI gate:"
chk "catalog enforcement in CI"               "grep -rn 'tool-catalog\|tool_catalog' .github/workflows/*.yml | grep -q ."
chk "check-tool-catalog script"               "[ -f scripts/check-tool-catalog.mjs ]"
echo "P2-03 perf budget gate:"
chk "budget.json"                             "[ -f scripts/budget.json ] || [ -f budget.json ]"
chk "perf CI workflow"                        "grep -rln 'budget' .github/workflows/*.yml | grep -q ."
echo "P2-04 nightly fuzzing:"
chk "fuzz workflow"                           "grep -rn 'fuzz' .github/workflows/*.yml | grep -qi ."
echo "P2-05 spec-before-code:"
chk "SPEC_TEMPLATE.md"                        "find . -name 'SPEC_TEMPLATE.md' -not -path './node_modules/*' | grep -q ."
echo "P2-06 interop report UI:"
chk "interop report component"                "grep -rli 'interop' src --include='*.tsx' | grep -q ."

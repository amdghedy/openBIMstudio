/** Schedule types — v2 with grouping, formulas, formatting, snapshots. */

export type ScheduleSource = "authored" | "ifc" | "mixed";

export type ColumnFormat =
  | "text"
  | "number"
  | "length"
  | "area"
  | "volume"
  | "count"
  | "currency"
  | "percent"
  | "date"
  | "formula";

/** A column in the schedule. */
export interface ScheduleColumn {
  key: string;
  header: string;
  format: ColumnFormat;
  unit?: string;
  width?: number;
  hidden?: boolean;
  /** For format: "formula". The expression source. */
  formula?: string;
  /** Optional tooltip text. */
  help?: string;
}

/** One level of grouping. Rows are grouped by the column key, in order. */
export interface GroupLevel {
  key: string;
  /** Optional bucket function applied to the value before grouping. */
  bucket?:
    | "none"
    | "thousands"
    | "level"
    | "firstLetter"
    | "ifcPrefix";
  /** Show a subtotal row after each group. */
  subtotal?: boolean;
  /** Collapsed by default when the schedule opens. */
  collapsed?: boolean;
}

export type ConditionOperator =
  | "eq"
  | "neq"
  | "gt"
  | "gte"
  | "lt"
  | "lte"
  | "contains"
  | "empty"
  | "notempty";

export interface ConditionalRule {
  id: string;
  /** Column key, or "*" for entire row. */
  column: string;
  op: ConditionOperator;
  value?: string | number;
  /** Optional formula expression — if set, condition is satisfied when
   *  expression evaluates to a truthy value. */
  formula?: string;
  /** CSS color, or a token like "#fca5a5". */
  bg?: string;
  fg?: string;
  /** If true, apply to the whole row rather than just the target column. */
  wholeRow?: boolean;
}

export interface SortKey {
  key: string;
  dir: "asc" | "desc";
}

export interface ScheduleRow {
  id: string;
  source: ScheduleSource;
  values: Record<string, string | number | null>;
  /** Group path — array of group values, one per group level. */
  groupPath?: (string | number)[];
  /** True if this row is a subtotal row generated by the generator. */
  subtotal?: boolean;
  /** Depth in the group tree (0 = top-level, -1 = data row). */
  depth?: number;
  /** Column keys that are subtotalable for this row. */
  subtotalValues?: Record<string, number>;
  link?: {
    kind: "authored" | "ifc";
    modelId?: string;
    localId?: number;
    authoredId?: string;
  };
}

export interface ScheduleDefinition {
  id: string;
  name: string;
  description?: string;
  /** Template this was created from, if any. */
  templateId?: string;
  category: string | null;
  levelName: string | null;
  columns: ScheduleColumn[];
  grouping?: GroupLevel[];
  sortBy?: string;
  sortKeys?: SortKey[];
  conditionalFormatting?: ConditionalRule[];
  /** Whether the schedule pulls quantities from the takeoff engine. */
  useLiveQuantities?: boolean;
  /** Whether the schedule pulls cost items and line costs. */
  useCostData?: boolean;
  /** Whether subtotal rows are shown (per group level, plus grand total). */
  showTotals?: boolean;
  /** Saved timestamp of when this definition was last edited. */
  updatedAt?: number;
}

export interface ScheduleRun {
  definition: ScheduleDefinition;
  rows: ScheduleRow[];
  /** Totals per column (grand total across all rows). */
  totals: Record<string, number>;
  /** Subtotals per group path per column. */
  groupTotals?: Record<string, Record<string, number>>;
  generatedAt: number;
  /** Snapshot ID for diffing — set on request. */
  snapshotId?: string;
}

/** Compact snapshot for diffing schedules between revisions. */
export interface ScheduleSnapshot {
  id: string;
  label: string;
  definitionId: string;
  takenAt: number;
  /** Row id → serialized values. */
  rows: Record<string, Record<string, string | number | null>>;
}